#!/usr/bin/env python3
"""Render docs/mcp-contract.md and the admin action catalog from mcp.json.

Response columns are derived by running each query against the migrated schema,
so the documented shapes cannot drift from the SQL. Use --check to fail when the
committed outputs are stale.
"""

import json
import re
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "mcp.json"
MIGRATIONS = ROOT / "migrations.json"
DOC = ROOT / "docs" / "mcp-contract.md"
CATALOG = ROOT / "web" / "src" / "generated" / "mcpCatalog.ts"

ERROR_CODES = [
    ("unauthenticated", "401", "No valid PAS session. Emitted by the platform before any SQL runs."),
    ("forbidden", "403", "The caller lacks a declared app role or the action is unavailable to this token. Emitted by the platform."),
    ("invalid_argument", "400", "A parameter fails its declared type, enum, min, max or maxLength. The body names the parameter path and a remediation. Target contract: the platform validates declared parameters before SQL runs."),
    ("constraint", "409", "A write violates a uniqueness or CHECK constraint, for example reusing a caller-supplied id for a not-idempotent create. Clients may treat this as already applied only when the original call is known to have succeeded."),
]
OUTCOME_NOT_APPLIED = (
    "not_applied",
    "A write that reports 0 changes was not applied. Causes: the target is not in the caller's club, the caller lacks the club role, the target is already in that state, or a value failed an in-SQL guard (for example an availability outside the enum). Clients must surface this and must not report success."
)

IDEMPOTENCY = {
    "read-only": "Reads never change state.",
    "idempotent": "Repeating the call with the same arguments leaves the same state. A repeat may report 0 changes (for example, a claim already consumed).",
    "not-idempotent": "Each call creates a new record. Retrying with the same caller-supplied id fails with a constraint error. Generate a new id only for a genuinely new record.",
    "append-only": "Writes an event row. Each call appends one row; do not retry blindly.",
}

PAGING = (
    "Every list read accepts `limit` (1 to 100, default 100) and `offset` (0 or more). Rows are ordered by a documented key with a unique tie-break, so consecutive pages do not overlap or skip rows. A page shorter than `limit` is the last page. Versioned reads return `updated_at` in epoch milliseconds (or the record's creation time when it has never been updated); compare it to detect change."
)


def load():
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    migrations = json.loads(MIGRATIONS.read_text(encoding="utf-8"))["migrations"]
    db = sqlite3.connect(":memory:")
    for migration in migrations:
        db.executescript(migration["sql"])
    return manifest["tools"], db


def bindings(tool):
    values = {name: None for name in re.findall(r":(\w+)", tool["sql"])}
    values.update({"__user_id": "contract-user", "__now": 1})
    for name, spec in tool.get("params", {}).items():
        if name in values:
            values[name] = spec.get("default", 1 if spec.get("type") == "integer" else "")
    if "limit" in values:
        values["limit"] = 1
    if "offset" in values:
        values["offset"] = 0
    if "rows" in values:
        values["rows"] = "[]"
    return values


def returns(tool, db):
    if tool["operation"] != "query":
        return ["changes (rows written; 0 means not applied)"]
    cursor = db.execute(tool["sql"], bindings(tool))
    return [column[0] for column in cursor.description]


def param_summary(spec):
    parts = [spec.get("type", "string")]
    if "default" in spec:
        parts.append(f"default {json.dumps(spec['default'])}")
    if "min" in spec:
        parts.append(f"min {spec['min']}")
    if "max" in spec:
        parts.append(f"max {spec['max']}")
    if "maxLength" in spec:
        parts.append(f"maxLength {spec['maxLength']}")
    if "enum" in spec:
        parts.append("one of " + ", ".join(f"`{value}`" for value in spec["enum"]))
    return "; ".join(parts)


def render_doc(tools, db):
    lines = [
        "# Tennis Clubs MCP contract",
        "",
        "<!-- Generated by scripts/render_mcp_catalog.py from mcp.json. Do not edit by hand. -->",
        "",
        "The MCP is the administrative integration surface for club data. The action manifest is `mcp.json`; the platform registers it on every deploy. This document is generated from that manifest and from the migrated schema, so response shapes are the columns each action's SQL really returns.",
        "",
        "## Access model",
        "",
        "- Every action requires an authenticated PAS session (`requires_auth`). The caller is the verified PAS user id, passed to SQL as `:__user_id`. Callers never supply their own identity.",
        "- Club-scoped actions check an active `club_memberships` row for the target club in the same SQL statement. Roles come from that row, not from PAS app roles.",
        "- Team-scoped actions check an active `team_players` row or an accepted `team_memberships` row for a fixture's team.",
        "- The platform owner override is not implemented. PAS app roles are not consulted by any action.",
        "- The app's UI checks are conveniences. Every restricted read and write is enforced in the action SQL.",
        "",
        "## Roles",
        "",
        "| Role | Server permissions |",
        "| --- | --- |",
        "| `admin`, `convenor`, `manager` | Club setup, invites, managed fixtures, rosters, match-day status, results, imports, import reports, audit trail, authorised document metadata. Convenor has the same server powers as manager. |",
        "| `player` | Own team's fixtures and roster, and own availability only. |",
        "| `parent` | No club-level action. Team access exists only through an explicit team membership row, as for a player. |",
        "",
        "## Errors",
        "",
        "A refused or failed call uses the platform's error envelope: the `code` is the server's `error` field and the body carries the detail. Codes this contract relies on:",
        "",
        "| Code | HTTP | Meaning |",
        "| --- | --- | --- |",
    ]
    for code, status, meaning in ERROR_CODES:
        lines.append(f"| `{code}` | {status} | {meaning} |")
    lines += [
        "",
        f"Client outcome, not a platform code: `{OUTCOME_NOT_APPLIED[0]}`. {OUTCOME_NOT_APPLIED[1]}",
        "",
        "Only `forbidden` (a missing declared app role, from the SDK's `ActionError`) is confirmed by the SDK in this repository. The other codes, and the `field` and `remediation` envelope fields, are the target contract; the platform runtime is not in this repository and they are unverified here.",
        "",
        "## Idempotency",
        "",
    ]
    for name, text in IDEMPOTENCY.items():
        lines.append(f"- **{name}**: {text}")
    lines += ["", "## Pagination, filtering and versioning", "", PAGING, "", "Filters are optional parameters that default to `null` (no filter). Declared filters: `list_managed_fixtures.status`, `list_club_teams.division_id`, `list_import_reports.kind`, `list_authorised_documents.fixture_id`.", "", "## Audit trail", "", "Every audited write has a matching `record_audit_event` action name. The write's client calls `record_audit_event` with `outcome` `succeeded` or `refused`, and `action`, `target_type` and `target_id` naming the change. The actor is always the authenticated caller. Player availability changes are recorded by the append-only `log_*` actions instead.", "", "Limitation: the write and its audit record are separate statements. A client that does not call `record_audit_event` leaves no record. Completeness therefore depends on the client. Server-atomic auditing needs a multi-statement action, which this manifest does not yet use.", "", "## Redaction", "", "Fields withheld from an audience are listed per action. Player-facing reads never select convenor phone numbers, roster contact details, scorecard storage keys, or submitter identities. Document metadata is limited to presence, scores and timestamps; storage keys are never returned by `list_authorised_documents`.", "", "## Discovery", "", "The action catalog is shown to club administrators on the Club setup screen (generated from this manifest, containing names, roles and parameters but no SQL). The platform hosts the MCP endpoint for this app; its address is not stored in this repository.", "", "## Actions", ""]
    lines += [
        "| Action | Operation | Roles | Audience | Idempotency | Audit | Paging | Versioned |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for tool in tools:
        c = tool["contract"]
        roles = ", ".join(f"`{r}`" for r in c["roles"]) or f"`{c['access']}`"
        lines.append(
            f"| `{tool['name']}` | {tool['operation']} | {roles} | {c['audience']} | {c['idempotency']} | {'yes' if c['audit'] else 'no'} | {'yes' if c['paging'] else 'no'} | {'yes' if c['versioned'] else 'no'} |"
        )
    for tool in tools:
        c = tool["contract"]
        lines += ["", f"### `{tool['name']}`", "", tool["description"], ""]
        lines.append(f"- Access: {c['access']}; roles: {', '.join(c['roles']) or 'none (see access)'}; audience: {c['audience']}.")
        lines.append(f"- Idempotency: {c['idempotency']}. Audit: {'record with `record_audit_event`' if c['audit'] else 'not required'}.")
        if c["redacts"]:
            lines.append("- Withheld fields: " + ", ".join(f"`{field}`" for field in c["redacts"]) + ".")
        params = tool.get("params", {})
        if params:
            lines += ["", "| Parameter | Constraints |", "| --- | --- |"]
            for name, spec in params.items():
                lines.append(f"| `{name}` | {param_summary(spec)} |")
        else:
            lines.append("- Parameters: none.")
        cols = returns(tool, db)
        lines += ["", "Returns: " + (", ".join(f"`{column}`" for column in cols) if tool["operation"] == "query" else "`changes`: rows written; 0 means not applied.")]
    return "\n".join(lines) + "\n"


def render_catalog(tools):
    entries = []
    for tool in tools:
        c = tool["contract"]
        entries.append({
            "name": tool["name"],
            "description": tool["description"],
            "operation": tool["operation"],
            "roles": c["roles"],
            "access": c["access"],
            "audience": c["audience"],
            "idempotency": c["idempotency"],
            "audit": c["audit"],
            "paging": c["paging"],
            "versioned": c["versioned"],
            "params": [{"name": name, **{k: v for k, v in spec.items() if k in ("type", "default", "min", "max", "enum")}} for name, spec in tool.get("params", {}).items()],
        })
    body = json.dumps(entries, indent=2, ensure_ascii=False)
    return (
        "// Generated by scripts/render_mcp_catalog.py from mcp.json. Do not edit by hand.\n"
        "export interface McpCatalogParam {\n"
        "  name: string\n"
        "  type: string\n"
        "  default?: string | number | null\n"
        "  min?: number\n"
        "  max?: number\n"
        "  enum?: string[]\n"
        "}\n\n"
        "export interface McpCatalogEntry {\n"
        "  name: string\n"
        "  description: string\n"
        "  operation: string\n"
        "  roles: string[]\n"
        "  access: string\n"
        "  audience: string\n"
        "  idempotency: string\n"
        "  audit: boolean\n"
        "  paging: boolean\n"
        "  versioned: boolean\n"
        "  params: McpCatalogParam[]\n"
        "}\n\n"
        f"export const MCP_CATALOG: readonly McpCatalogEntry[] = {body}\n"
    )


def main():
    tools, db = load()
    outputs = {DOC: render_doc(tools, db), CATALOG: render_catalog(tools)}
    if "--check" in sys.argv:
        stale = [path for path, text in outputs.items() if not path.exists() or path.read_text(encoding="utf-8") != text]
        if stale:
            print("stale generated output: " + ", ".join(str(path.relative_to(ROOT)) for path in stale))
            print("run: python3 scripts/render_mcp_catalog.py")
            return 1
        print("generated MCP contract outputs are current")
        return 0
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
